"""Channel inset for the Rhine/Britain box: Kent + the Gallic coast, Natural Earth 10m land.
Usage: GEO_DIR=path/to/geo python3 tools/build_channel.py src/data/channel.js  (needs ne_10m_land.geojson)
Equirectangular with cos(lat) scaling (fine at this scale). Panel viewBox: 0 0 168 214."""
import json, math, os, sys
GEO = os.environ.get('GEO_DIR', 'geo'); OUT = sys.argv[1]
W, H = 168, 214
LON0, LON1, LAT0, LAT1 = 0.55, 2.35, 50.45, 51.52
k = math.cos(math.radians((LAT0 + LAT1) / 2))
sx = W / ((LON1 - LON0) * k); sy = H / (LAT1 - LAT0); S = min(sx, sy)
def P(lon, lat): return ((lon - LON0) * k * S, (LAT1 - lat) * S)
def dp(pts, tol):
    if len(pts) < 3: return pts
    keep = [False] * len(pts); keep[0] = keep[-1] = True; st = [(0, len(pts) - 1)]
    while st:
        a, b = st.pop(); ax, ay = pts[a]; bx, by = pts[b]; dx, dy = bx - ax, by - ay; L = math.hypot(dx, dy) or 1e-9
        best, bi = -1, -1
        for i in range(a + 1, b):
            px, py = pts[i]; d = abs(dy * px - dx * py + bx * ay - by * ax) / L
            if d > best: best, bi = d, i
        if best > tol: keep[bi] = True; st += [(a, bi), (bi, b)]
    return [p for p, kk in zip(pts, keep) if kk]
def ring(pts):
    if len(pts) < 6: return pts
    m = len(pts) // 2; return dp(pts[:m + 1], 0.25)[:-1] + dp(pts[m:], 0.25)
def clip(poly, x0=-20, y0=-20, x1=W + 20, y1=H + 20):
    def c(pts, ins, cut):
        out = []
        for i, cur in enumerate(pts):
            prev = pts[i - 1]
            if ins(cur):
                if not ins(prev): out.append(cut(prev, cur))
                out.append(cur)
            elif ins(prev): out.append(cut(prev, cur))
        return out
    X = lambda v: (lambda a, b: (v, a[1] + (b[1] - a[1]) * (v - a[0]) / ((b[0] - a[0]) or 1e-9)))
    Y = lambda v: (lambda a, b: (a[0] + (b[0] - a[0]) * (v - a[1]) / ((b[1] - a[1]) or 1e-9), v))
    for ins, cut in ((lambda p: p[0] >= x0, X(x0)), (lambda p: p[0] <= x1, X(x1)), (lambda p: p[1] >= y0, Y(y0)), (lambda p: p[1] <= y1, Y(y1))):
        if not poly: break
        poly = c(poly, ins, cut)
    return poly
f = lambda p: f'{p[0]:.1f},{p[1]:.1f}'
d = json.load(open(f'{GEO}/ne_10m_land.geojson'))
britain, gaul = [], []
for ft in d['features']:
    g = ft['geometry']
    for poly in (g['coordinates'] if g['type'] == 'MultiPolygon' else [g['coordinates']]):
        r = poly[0]
        if not any(LON0 - 1 < x < LON1 + 1 and LAT0 - 1 < y < LAT1 + 1 for x, y in r): continue
        pr = clip(ring([P(x, y) for x, y in r]))
        if len(pr) < 3: continue
        cy = sum(y for _, y in r) / len(r)
        (britain if cy > 51.0 and sum(x for x, _ in r) / len(r) < 1.0 else gaul).append('M' + ' L'.join(f(p) for p in pr) + ' Z')
pl = {'portus': P(1.6147, 50.7264), 'deal': P(1.4006, 51.2226), 'dover': P(1.31, 51.125), 'thames': P(0.75, 51.47)}
js = f"""/* Channel inset (viewBox 0 0 {W} {H}) — Natural Earth 1:10m land, public domain; generated by tools/build_channel.py */
export const KENT = {json.dumps(' '.join(britain))};
export const GAUL_COAST = {json.dumps(' '.join(gaul))};
export const CH = {json.dumps({k: [round(v[0], 1), round(v[1], 1)] for k, v in pl.items()})};
"""
open(OUT, 'w').write(js); print(len(js), len(britain), len(gaul), pl)
