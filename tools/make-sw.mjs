/*
 * Writes dist/sw.js after the build: the service worker that keeps a copy of the presentation on
 * the device. Every file is stored under its content hash, so a new deploy replaces exactly the files
 * that changed. The game lab, its scoreboard API and photos from other sites are never stored.
 *
 *   node tools/make-sw.mjs dist
 */
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const dist = process.argv[2] || 'dist';
const all = [];
(function walk(dir) {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) walk(p); else all.push(relative(dist, p).split('\\').join('/'));
  }
}(dist));

const skip = /(^|\/)\.|\.map$|^sw\.js$|^game-lab\.html$|^assets\/(lab-|Percee|fp3d)|^fonts\/(.*-ext\.woff2|OFL\.txt)$/;
const hash = (f) => createHash('sha1').update(readFileSync(join(dist, f))).digest('hex').slice(0, 10);
const files = Object.fromEntries(all.filter((f) => !skip.test(f)).sort().map((f) => [f, hash(f)]));

// what the first screen needs is stored at install; the rest follows one file at a time
const html = readFileSync(join(dist, 'index.html'), 'utf8');
const entry = new Set([...html.matchAll(/(?:src|href)="\.\/(assets\/[^"]+)"/g)].map((m) => m[1]));
const shell = Object.keys(files).filter((f) => f === 'index.html' || entry.has(f) || /^fonts\/|^(manifest\.webmanifest|favicon\.svg|apple-touch-icon\.png)$/.test(f));
const later = Object.keys(files).filter((f) => !shell.includes(f)).sort((a, b) => (b.startsWith('assets/') - a.startsWith('assets/')) || a.localeCompare(b));
const version = createHash('sha1').update(JSON.stringify(files)).digest('hex').slice(0, 10);

const worker = `/* generated by tools/make-sw.mjs: version ${version} */
const FILES = ${JSON.stringify(files)};
const SHELL = ${JSON.stringify(shell)};
const LATER = ${JSON.stringify(later)};
const CACHE = 'alesia-story';
const scope = self.registration.scope;
const root = new URL(scope).pathname;
const keyOf = (file) => scope + file + '?v=' + FILES[file];
const fileOf = (url) => { const u = new URL(url); return u.origin === location.origin && u.pathname.startsWith(root) ? u.pathname.slice(root.length) : null; };

async function digest(response) {
  const bytes = await crypto.subtle.digest('SHA-1', await response.clone().arrayBuffer());
  return [...new Uint8Array(bytes)].map((b) => b.toString(16).padStart(2, '0')).join('').slice(0, 10);
}
const isExact = async (file, response) => response.ok && response.status === 200 && (file === 'index.html' || await digest(response) === FILES[file]);

/* Uses the browser's copy when it is the right file, so nothing is downloaded twice; an out-of-date copy is fetched again. */
async function store(cache, file) {
  if (await cache.match(keyOf(file))) return;
  let response = await fetch(scope + file, file === 'index.html' ? { cache: 'reload' } : {});
  if (!await isExact(file, response)) response = await fetch(scope + file, { cache: 'reload' });
  if (await isExact(file, response)) await cache.put(keyOf(file), response);
}

let filling = null;
const fill = () => filling || (filling = (async () => {
  if (self.navigator.connection && self.navigator.connection.saveData) return;
  const cache = await caches.open(CACHE);
  for (const file of LATER) { try { await store(cache, file); } catch { /* offline: the next visit carries on */ } }
})().finally(() => { filling = null; }));

self.addEventListener('install', (event) => {
  self.skipWaiting();
  event.waitUntil(caches.open(CACHE).then((cache) => Promise.all(SHELL.map((file) => store(cache, file)))));
});
self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    const current = new Set(Object.keys(FILES).map(keyOf));
    for (const request of await cache.keys()) if (!current.has(request.url)) await cache.delete(request);
    await self.clients.claim();
  })());
});
self.addEventListener('message', (event) => { if (event.data === 'precache') event.waitUntil(fill()); });

async function page(request) {
  const cache = await caches.open(CACHE);
  try {
    const response = await Promise.race([fetch(request), new Promise((_, reject) => { setTimeout(reject, 4000); })]);
    if (response.ok && response.status === 200) await cache.put(keyOf('index.html'), response.clone());
    return response;
  } catch {
    return (await cache.match(keyOf('index.html'))) || fetch(request);
  }
}
async function asset(request, file) {
  const cache = await caches.open(CACHE);
  const hit = await cache.match(keyOf(file));
  if (hit) return hit;
  const response = await fetch(request);
  if (response.type === 'basic' && await isExact(file, response)) await cache.put(keyOf(file), response.clone());
  return response;
}
self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET' || request.headers.has('range')) return;
  const file = fileOf(request.url);
  if (file === null || file.startsWith('api/')) return;
  if (request.mode === 'navigate') { if (file === '' || file === 'index.html') event.respondWith(page(request)); return; }
  if (file in FILES) event.respondWith(asset(request, file));
});
`;
writeFileSync(join(dist, 'sw.js'), worker);
console.log(`sw.js ${version}: ${Object.keys(files).length} files (${shell.length} at install, ${later.length} after)`);
